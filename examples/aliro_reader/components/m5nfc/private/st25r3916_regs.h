// ST25R3916 register transactions and configuration follow DS12484 Rev 8.
enum {
    ST25R3916_REG_IO2 = 0x01,
    ST25R3916_REG_OPERATION = 0x02,
    ST25R3916_REG_MODE = 0x03,
    ST25R3916_REG_BIT_RATE = 0x04,
    ST25R3916_REG_ISO14443A = 0x05,
    ST25R3916_REG_AUX = 0x0a,
    ST25R3916_REG_RX1 = 0x0b,
    ST25R3916_REG_RX2 = 0x0c,
    ST25R3916_REG_RX3 = 0x0d,
    ST25R3916_REG_RX4 = 0x0e,
    ST25R3916_REG_MASK_RX_TIMER = 0x0f,
    ST25R3916_REG_NO_RESPONSE_TIMER = 0x10,
    ST25R3916_REG_TIMER_CONTROL = 0x12,
    ST25R3916_REG_IRQ_MASK = 0x16,
    ST25R3916_REG_IRQ = 0x1a,
    ST25R3916_REG_FIFO_STATUS = 0x1e,
    ST25R3916_REG_COLLISION = 0x20,
    ST25R3916_REG_TX_BYTES = 0x22,
    ST25R3916_REG_TX_DRIVER = 0x28,
    ST25R3916_REG_REGULATOR = 0x2c,
    ST25R3916_REG_IC_IDENTITY = 0x3f,
    ST25R3916_REG_OVERSHOOT1 = 0x130,
    ST25R3916_REG_OVERSHOOT2 = 0x131,
    ST25R3916_REG_UNDERSHOOT1 = 0x132,
    ST25R3916_REG_UNDERSHOOT2 = 0x133,
    ST25R3916_REG_CORRELATOR1 = 0x10c,
    ST25R3916_REG_CORRELATOR2 = 0x10d,
};

enum {
    ST25R3916_CMD_RESET = 0xc1,
    // DS12484 table 13: C0/C1 reset the IC; C2/C3 stop without losing RF setup.
    ST25R3916_CMD_STOP = 0xc2,
    ST25R3916_CMD_TX_CRC = 0xc4,
    ST25R3916_CMD_TX_NO_CRC = 0xc5,
    ST25R3916_CMD_WUPA = 0xc7,
    ST25R3916_CMD_INITIAL_FIELD_ON = 0xc8,
    ST25R3916_CMD_RESET_RX_GAIN = 0xd5,
    ST25R3916_CMD_ADJUST_REGULATORS = 0xd6,
};

#define ST25R3916_IRQ_OSC 0x80000000UL
#define ST25R3916_IRQ_RX_START 0x20000000UL
#define ST25R3916_IRQ_RX_END 0x10000000UL
#define ST25R3916_IRQ_TX_END 0x08000000UL
#define ST25R3916_IRQ_COLLISION 0x04000000UL
#define ST25R3916_IRQ_DIRECT_COMMAND 0x00800000UL
#define ST25R3916_IRQ_NO_RESPONSE 0x00400000UL
#define ST25R3916_IRQ_RF_COLLISION 0x00040000UL
#define ST25R3916_IRQ_RF_GUARD 0x00020000UL
#define ST25R3916_IRQ_CRC 0x00008000UL
#define ST25R3916_IRQ_RX_ERROR 0x00007000UL
#define ST25R3916_IRQ_FIELD_ON 0x00000020UL

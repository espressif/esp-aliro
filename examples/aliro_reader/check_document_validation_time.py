"""Check the frozen fixture clock and generate its UTC date annotation."""

import re
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path


def main() -> int:
    config_path = Path("examples/aliro_reader/main/Kconfig.projbuild")
    source_path = Path(__file__).resolve().parents[2] / config_path
    config = source_path.read_text(encoding="utf-8")
    defaults = list(
        re.finditer(
            r'^config EXAMPLE_DOCUMENT_VALIDATION_TIME\n'
            r'(?:[ \t].*\n|\n)*?'
            r'(?P<comment>    # Generated by check_document_validation_time\.py:.*\n)?'
            r'(?P<default>    default (?P<timestamp>[0-9]+)[ \t]*)$',
            config,
            re.MULTILINE,
        )
    )
    if len(defaults) != 1:
        print(f"{config_path}: expected one numeric validation-time default", file=sys.stderr)
        return 1

    default = defaults[0]
    timestamp = int(default.group("timestamp"))
    now = datetime.now(timezone.utc).replace(microsecond=0)
    earliest = now + timedelta(days=30)
    latest = now + timedelta(days=365)
    if not earliest.timestamp() <= timestamp <= latest.timestamp():
        print(
            f"{config_path}: CONFIG_EXAMPLE_DOCUMENT_VALIDATION_TIME={timestamp} "
            f"must be 30–365 days ahead of current UTC "
            f"({earliest:%Y-%m-%dT%H:%M:%SZ} to {latest:%Y-%m-%dT%H:%M:%SZ}). "
            "Update the frozen test-clock default.",
            file=sys.stderr,
        )
        return 1

    utc_date = datetime.fromtimestamp(timestamp, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    comment = f"    # Generated by {Path(__file__).name}: {utc_date}\n"
    start = default.start("comment") if default.group("comment") else default.start("default")
    updated = config[:start] + comment + config[default.start("default"):]
    if updated != config:
        source_path.write_text(updated, encoding="utf-8")
        print(f"{config_path}: updated generated UTC date; re-run pre-commit")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
